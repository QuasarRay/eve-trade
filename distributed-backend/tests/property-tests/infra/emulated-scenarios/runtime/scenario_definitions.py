def matching_scenarios(name: str) -> list[ScenarioDefinition]:
    """Return every matching definition in canonical precedence order."""
    return [scenario for scenario in SCENARIOS if scenario.matches(name)]


def scenario_for(name: str) -> ScenarioDefinition | None:
    matches = matching_scenarios(name)
    return matches[0] if matches else None


def scenario_ids() -> set[str]:
    ids = [scenario.scenario_id for scenario in SCENARIOS]
    if len(ids) != len(set(ids)):
        raise ValueError("canonical scenario definitions contain duplicate IDs")
    return set(ids)
