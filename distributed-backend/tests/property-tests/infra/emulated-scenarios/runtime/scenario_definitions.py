@dataclass(frozen=True)
class ScenarioDefinition:
    scenario_id: str
    purpose: str
    selectors: tuple[str, ...]
    status: str
    deployed_components: tuple[str, ...]
    workload: str
    action_kind: str
    target: str
    affected_path: str
    activation_barrier: str
    independent_witness: str
    release_barrier: str
    uses_litmus: bool = False
    litmus_experiment: str | None = None
    application_clock_mode: str = "REAL_UNINJECTED"
    blocker: str | None = None
    exclusions: tuple[str, ...] = ()

    def matches(self, name: str) -> bool:
        return any(re.search(pattern, name) for pattern in self.selectors) and not any(
            re.search(pattern, name) for pattern in self.exclusions
        )


